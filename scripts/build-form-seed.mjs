// Builds supabase/seed/04_post_forms.sql from supabase/forms/post/*.json (one file per post type = the source of truth
// for forms). Every file is validated against the shared FormSchema rules and its title/description placeholders must
// name a field of the form (or city/type). Run: pnpm forms:build
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { FormSchema } from "../packages/shared/src/formSchema.ts";

const dir = new URL("../supabase/forms/post/", import.meta.url);
const out = new URL("../supabase/seed/04_post_forms.sql", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const errors = [];
const rows = [];

for (const file of files) {
  const raw = JSON.parse(readFileSync(new URL(file, dir), "utf8"));
  const parsed = FormSchema.safeParse(raw);
  if (!parsed.success) { errors.push(`${file}: ${parsed.error.issues.map((i) => i.message).join("; ")}`); continue; }
  const s = parsed.data;
  if (file !== `${s.type_slug}.json`) errors.push(`${file}: type_slug "${s.type_slug}" must match the file name`);
  const keys = new Set([...s.fields.map((f) => f.key), "city", "type"]);
  for (const t of [s.title_template, s.description_template, s.title_template_hi ?? "", s.description_template_hi ?? ""]) {
    for (const [, k] of t.matchAll(/\{\{(\w+)\}\}/g)) if (!keys.has(k)) errors.push(`${file}: template uses unknown field {{${k}}}`);
  }
  const keyList = s.fields.map((f) => f.key);
  const dupes = keyList.filter((k, i) => keyList.indexOf(k) !== i);
  if (dupes.length) errors.push(`${file}: duplicate field keys ${dupes.join(", ")}`);
  rows.push(s);
}
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const sql = `-- GENERATED by scripts/build-form-seed.mjs from supabase/forms/post/*.json. Do not edit by hand: change the JSON, run
-- \`pnpm forms:build\`, then apply the seeds (they are idempotent; existing rows are updated, nothing is deleted).
-- Older versions stay for posts created with them; the app always uses the highest active version.
insert into public.form_schemas (target, type_slug, version, fields, title_template, description_template, title_template_hi, description_template_hi) values
${rows.map((s) => `(${q(s.target)}, ${q(s.type_slug)}, ${s.version}, ${q(JSON.stringify(s.fields))}::jsonb, ${q(s.title_template)}, ${q(s.description_template)}, ${q(s.title_template_hi)}, ${q(s.description_template_hi)})`).join(",\n")}
on conflict (target, type_slug, version) do update set fields = excluded.fields, title_template = excluded.title_template,
  description_template = excluded.description_template, title_template_hi = excluded.title_template_hi,
  description_template_hi = excluded.description_template_hi, active = true;
`;
writeFileSync(out, sql);
console.log(`${rows.length} forms valid -> supabase/seed/04_post_forms.sql`);
